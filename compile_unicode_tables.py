#!/usr/bin/env python3
"""
Write src/unicode_tables.js from the pinned interpreter's own Unicode data.

The Worker never asks the engine it runs on where a Unicode table can answer: the engine's own tables follow its own
Unicode version, and the edge moves without us. The classes a rule or a helper reads (letter or number, mark, other or
separator, digit, identifier, unassigned) are written here, by range, from the interpreter the pip scanner is measured on. A code point
the pinned data has not assigned is a plain unassigned character to every reader in the Worker.

    /opt/homebrew/opt/python@3.14/bin/python3.14 compile_unicode_tables.py

It refuses to run on any other Unicode version, so the file cannot drift by accident.
"""
import sys
import unicodedata
from pathlib import Path

PINNED = "16.0.0"
OUT = Path(__file__).parent / "src" / "unicode_tables.js"


def ranges(test):
    out, start, prev = [], None, None
    for cp in range(0x110000):
        hit = test(cp)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def cat(cp):
    return "Cs" if 0xD800 <= cp <= 0xDFFF else unicodedata.category(chr(cp))


def main():
    if unicodedata.unidata_version != PINNED:
        sys.exit("this interpreter reads Unicode %s; the tables are pinned to %s" % (unicodedata.unidata_version, PINNED))
    def xid_start(cp):
        return cp != 0x5F and chr(cp).isidentifier() if not 0xD800 <= cp <= 0xDFFF else False

    def xid_continue(cp):
        return ("_" + chr(cp)).isidentifier() if not 0xD800 <= cp <= 0xDFFF else False

    # Property name as a \\p{...} spells it -> membership. Letter and number are listed apart so `\\p{L}\\p{N}` reads as it is written.
    tables = [
        ("L", lambda cp: cat(cp)[0] == "L"),
        ("N", lambda cp: cat(cp)[0] == "N"),
        ("Nd", lambda cp: cat(cp) == "Nd"),
        ("M", lambda cp: cat(cp)[0] == "M"),
        ("C", lambda cp: cat(cp)[0] == "C"),
        ("Z", lambda cp: cat(cp)[0] == "Z"),
        ("XID_Start", xid_start),
        ("XID_Continue", xid_continue),
        ("Cn", lambda cp: cat(cp) == "Cn"),
    ]
    lines = [
        "// AUTO-GENERATED by compile_unicode_tables.py - DO NOT EDIT",
        "// Source: Python %s, Unicode %s. Flat [first, last] pairs of code points, inclusive." % (sys.version.split()[0], unicodedata.unidata_version),
        'export const PINNED_UNICODE = "%s";' % unicodedata.unidata_version,
    ]
    lines.append("export const UNICODE_PROPERTIES = {")
    for name, test in tables:
        rs = ranges(test)
        lines.append("// %s: %d ranges" % (name, len(rs)))
        row = []
        lines.append('  "%s": [' % name)
        for lo, hi in rs:
            row.append("0x%x,0x%x" % (lo, hi))
            if len(row) == 8:
                lines.append("    " + ",".join(row) + ",")
                row = []
        if row:
            lines.append("    " + ",".join(row) + ",")
        lines.append("  ],")
    lines.append("};")
    # str.upper() has no context rule, so it is written whole: [code point, count, mapped code points...] for each character it changes.
    flat = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        up = chr(cp).upper()
        if up != chr(cp):
            flat += [cp, len(up)] + [ord(x) for x in up]
    lines.append("// UPPER")
    lines.append("export const UPPER_CASE = [")
    for i in range(0, len(flat), 16):
        lines.append("  " + ",".join(str(x) for x in flat[i:i + 16]) + ",")
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", OUT)


main()
