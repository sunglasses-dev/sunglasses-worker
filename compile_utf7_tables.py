#!/usr/bin/env python3
"""
Write src/utf7_tables.js from the interpreter's own Unicode data.

The UTF-7 reading of a run asks two questions of each decoded character: is it a letter (str.isalpha), and which
script it is written in (the first word of its Unicode name, Han and kana as one). The pip scanner answers both
from the interpreter's tables. The Worker answers them from this file, which is extracted from the same tables,
so a character is a letter or a script member there exactly where it is one in the interpreter. Nothing is retyped.

    python3 compile_utf7_tables.py
"""
import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).parent / "src" / "utf7_tables.js"
KANA_HAN = ("CJK", "HIRAGANA", "KATAKANA")


def script_key(char):
    word = unicodedata.name(char, "?").split(" ", 1)[0]
    return "CJK" if word in KANA_HAN else word


def runs():
    """(start, script id, letter) for every maximal stretch of code points that share both answers."""
    ids = {}
    out, prev = [], None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            now = ("?", False)         # a lone surrogate has no name and is not a letter
        else:
            char = chr(cp)
            now = (script_key(char), char.isalpha())
        if now != prev:
            out.append((cp, ids.setdefault(now[0], len(ids)), 1 if now[1] else 0))
            prev = now
    return out, len(ids)


def main():
    table, scripts = runs()
    lines = [
        "// AUTO-GENERATED by compile_utf7_tables.py - DO NOT EDIT",
        "// Source: Python %s, Unicode %s (%d stretches, %d scripts)"
        % (sys.version.split()[0], unicodedata.unidata_version, len(table), scripts),
        "// Each stretch is [first code point, script id * 2 + 1 when the character is a letter]; it runs to the next one.",
        "export const UTF7_STRETCHES = [",
    ]
    row = []
    for start, sid, alpha in table:
        row.append("%d,%d" % (start, sid * 2 + alpha))
        if len(row) == 12:
            lines.append("  " + ",".join(row) + ",")
            row = []
    if row:
        lines.append("  " + ",".join(row) + ",")
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", OUT, len(table), scripts)


if __name__ == "__main__":
    main()
